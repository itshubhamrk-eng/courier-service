-- =============================================================================
-- V110 — Business Customer Billing: invoices, invoice lines, invoice payments
--
-- An invoice bills ONE business customer for every non-cancelled booking not already on a live
-- invoice (shipments are matched to the customer on the consignor's mobile — a shipment stores
-- plain sender values, no customer id). A line is one shipment; a shipment can sit on one LIVE
-- line only (cancelling an invoice soft-deletes its lines, freeing the shipments to be billed
-- again). Bookings paid at the counter (payment mode PAID) are listed but counted as `prepaid`,
-- so the outstanding balance = total - prepaid - receipts.
--
-- Permission module CUSTOMER_BILLING (CREATE = generate, UPDATE = record payment, DELETE = cancel).
-- =============================================================================

CREATE TABLE customer_invoices (
    id            BINARY(16)   NOT NULL,
    company_id    BINARY(16)   NOT NULL,
    customer_id   BINARY(16)   NOT NULL,
    invoice_number VARCHAR(40) NOT NULL,
    invoice_date  DATE         NOT NULL,
    period_from   DATE         NOT NULL,
    period_to     DATE         NOT NULL,
    billing_frequency VARCHAR(15) NOT NULL,
    -- UNPAID | PARTLY_PAID | PAID | CANCELLED
    status        VARCHAR(20)  NOT NULL DEFAULT 'UNPAID',
    -- AUTO (billing cycle job) | MANUAL (generated by an admin)
    source        VARCHAR(10)  NOT NULL,
    shipments_count INT        NOT NULL DEFAULT 0,
    total_quantity  INT        NOT NULL DEFAULT 0,
    total_weight    DECIMAL(14, 3) NOT NULL DEFAULT 0,
    gst_amount      DECIMAL(14, 2) NOT NULL DEFAULT 0,
    total_amount    DECIMAL(14, 2) NOT NULL DEFAULT 0,
    prepaid_amount  DECIMAL(14, 2) NOT NULL DEFAULT 0,
    amount_paid     DECIMAL(14, 2) NOT NULL DEFAULT 0,
    remarks       VARCHAR(255) NULL,

    created_at TIMESTAMP(6) NOT NULL, created_by BINARY(16) NULL,
    updated_at TIMESTAMP(6) NOT NULL, updated_by BINARY(16) NULL,
    deleted    BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) NULL, deleted_by BINARY(16) NULL,
    version    BIGINT NOT NULL DEFAULT 0,

    PRIMARY KEY (id),
    -- never scoped by `deleted`: an invoice number, once issued, stays reserved
    UNIQUE KEY uk_cinv_company_number (company_id, invoice_number),
    KEY idx_cinv_company_customer (company_id, customer_id),
    KEY idx_cinv_company_status (company_id, status),
    KEY idx_cinv_customer_period (customer_id, source, period_to),
    CONSTRAINT fk_cinv_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci
  COMMENT = 'Business customer invoices (one per billing cycle / manual run)';

CREATE TABLE customer_invoice_lines (
    id          BINARY(16)   NOT NULL,
    company_id  BINARY(16)   NOT NULL,
    invoice_id  BINARY(16)   NOT NULL,
    shipment_id BINARY(16)   NOT NULL,
    shipment_number VARCHAR(50) NOT NULL,
    booking_date DATE        NULL,
    consignee   VARCHAR(150) NULL,
    destination_pincode VARCHAR(10) NULL,
    quantity    INT          NOT NULL DEFAULT 0,
    actual_weight DECIMAL(12, 3) NOT NULL DEFAULT 0,
    payment_mode VARCHAR(60) NULL,
    prepaid     BOOLEAN      NOT NULL DEFAULT FALSE,
    gst_amount  DECIMAL(14, 2) NOT NULL DEFAULT 0,
    amount      DECIMAL(14, 2) NOT NULL DEFAULT 0,

    created_at TIMESTAMP(6) NOT NULL, created_by BINARY(16) NULL,
    updated_at TIMESTAMP(6) NOT NULL, updated_by BINARY(16) NULL,
    deleted    BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) NULL, deleted_by BINARY(16) NULL,
    version    BIGINT NOT NULL DEFAULT 0,

    PRIMARY KEY (id),
    KEY idx_cinvl_invoice (company_id, invoice_id),
    KEY idx_cinvl_shipment (shipment_id, deleted),
    CONSTRAINT fk_cinvl_invoice FOREIGN KEY (invoice_id) REFERENCES customer_invoices (id) ON DELETE RESTRICT
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci
  COMMENT = 'One shipment on a business customer invoice';

CREATE TABLE customer_invoice_payments (
    id          BINARY(16)   NOT NULL,
    company_id  BINARY(16)   NOT NULL,
    invoice_id  BINARY(16)   NOT NULL,
    amount      DECIMAL(14, 2) NOT NULL,
    paid_on     DATE         NOT NULL,
    -- CASH | UPI | BANK_TRANSFER | CHEQUE | OTHER
    method      VARCHAR(20)  NOT NULL,
    reference   VARCHAR(100) NULL,
    remarks     VARCHAR(255) NULL,

    created_at TIMESTAMP(6) NOT NULL, created_by BINARY(16) NULL,
    updated_at TIMESTAMP(6) NOT NULL, updated_by BINARY(16) NULL,
    deleted    BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) NULL, deleted_by BINARY(16) NULL,
    version    BIGINT NOT NULL DEFAULT 0,

    PRIMARY KEY (id),
    KEY idx_cinvp_invoice (company_id, invoice_id),
    CONSTRAINT fk_cinvp_invoice FOREIGN KEY (invoice_id) REFERENCES customer_invoices (id) ON DELETE RESTRICT,
    CONSTRAINT ck_cinvp_amount CHECK (amount > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci
  COMMENT = 'Receipts against a business customer invoice';

-- --- permission catalogue: CUSTOMER_BILLING (128) ----------------------------------------
INSERT INTO permissions (id, permission_code, permission_name, module, resource, action,
                         display_order, required_feature_flag, is_system_permission, status,
                         created_at, updated_at, deleted, version)
SELECT UNHEX(REPLACE(UUID(), '-', '')), d.code, d.name, d.module, d.resource, d.action,
       d.display_order, NULL, TRUE, 'ACTIVE',
       UTC_TIMESTAMP(6), UTC_TIMESTAMP(6), FALSE, 0
FROM (
  SELECT 'CUSTOMER_BILLING_CREATE' AS code, 'Generate Customer Invoice' AS name, 'CUSTOMER_BILLING' AS module, 'customer-invoices' AS resource, 'CREATE' AS action, 1280 AS display_order
  UNION ALL SELECT 'CUSTOMER_BILLING_READ', 'View Customer Invoice', 'CUSTOMER_BILLING', 'customer-invoices', 'READ', 1281
  UNION ALL SELECT 'CUSTOMER_BILLING_UPDATE', 'Record Customer Invoice Payment', 'CUSTOMER_BILLING', 'customer-invoices', 'UPDATE', 1282
  UNION ALL SELECT 'CUSTOMER_BILLING_DELETE', 'Cancel Customer Invoice', 'CUSTOMER_BILLING', 'customer-invoices', 'DELETE', 1283
  UNION ALL SELECT 'CUSTOMER_BILLING_SEARCH', 'Search Customer Invoices', 'CUSTOMER_BILLING', 'customer-invoices', 'SEARCH', 1284
  UNION ALL SELECT 'CUSTOMER_BILLING_EXPORT', 'Export Customer Invoices', 'CUSTOMER_BILLING', 'customer-invoices', 'EXPORT', 1285
  UNION ALL SELECT 'CUSTOMER_BILLING_PRINT', 'Print Customer Invoice', 'CUSTOMER_BILLING', 'customer-invoices', 'PRINT', 1286
) AS d;

-- The login JWT is built from role_permissions rows (see V107): grant the new codes to every
-- existing company's COMPANY_ADMIN role. Same pattern as V98 / V107.
INSERT INTO role_permissions
    (id, company_id, role_id, permission_id, permission_code, created_at, updated_at, deleted, version)
SELECT UNHEX(REPLACE(UUID(), '-', '')), r.company_id, r.id, p.id, p.permission_code, NOW(6), NOW(6), 0, 0
FROM company_roles r
JOIN permissions p ON p.module = 'CUSTOMER_BILLING' AND p.deleted = 0
WHERE r.role_code = 'COMPANY_ADMIN' AND r.deleted = 0 AND r.status = 'ACTIVE'
  AND NOT EXISTS (SELECT 1 FROM role_permissions x
                  WHERE x.company_id = r.company_id AND x.role_id = r.id AND x.permission_id = p.id);

